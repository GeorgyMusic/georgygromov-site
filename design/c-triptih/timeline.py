def human(iso):
    y, m, d = map(int, iso.split('-'))
    return f"{d} {MONTHS[m-1]} {y}"


def season(iso):
    """Сезон с сентября по август: '2025/26'."""
    y, m = int(iso[:4]), int(iso[5:7])
    a = y if m >= 9 else y - 1
    return f"{a}/{str(a + 1)[2:]}"
